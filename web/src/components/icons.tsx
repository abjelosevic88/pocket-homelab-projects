export type IconName = keyof typeof paths | string

const ALIAS: Record<string, string> = { 'chevron-right': 'chevronRight', 'chevron-down': 'chevronDown', 'log-out': 'logout', 'calendar-days': 'calendarDays' }

export function Icon({ name, size = 16, className = '', style, title, fill, stroke, strokeWidth }: P & { name: IconName; strokeWidth?: number }) {
  const own = paths[ALIAS[name] || name]
  const filled = fill || name === 'more' || name === 'dot'
  return (
    <svg className={`icon ${className}`} style={style} width={size} height={size} viewBox="0 0 24 24" fill={filled ? 'currentColor' : 'none'} stroke="currentColor" strokeWidth={stroke ?? strokeWidth ?? 1.85} strokeLinecap="round" strokeLinejoin="round" aria-hidden={title ? undefined : true} role={title ? 'img' : undefined}>
      {title && <title>{title}</title>}
      {own ?? <path d={D[name] || D.circle} />}
    </svg>
  )
}

/** A list's mark: a ring in its colour with a soft fill. */
export function ListRing({ color, size = 14 }: { color?: string; size?: number }) {
  const c = color || 'var(--faint)'
  return (
    <svg className="list-ring" width={size} height={size} viewBox="0 0 16 16" aria-hidden>
      <circle cx="8" cy="8" r="6" fill={c} fillOpacity=".18" stroke={c} strokeWidth="2.2" />
    </svg>
  )
}

